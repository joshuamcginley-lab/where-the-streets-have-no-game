#!/usr/bin/env python3
"""MacPhisto reads the questions: one MP3 per trivia question, made through the ElevenLabs API.

    python3 tools/question-voice.py            # make any that are missing, remove unused ones, rebuild question-voice.js
    python3 tools/question-voice.py --index    # only rebuild question-voice.js

Each question's file is audio/q/<id>.mp3, where id is the first 10 hex digits of the SHA-1 of its
text (as the TV sees it), so editing a question makes a new file and the old one can be deleted.
question-voice.js maps each question's text to its id, its length, and its loudness 25 times a second (his lips).
Song questions aren't read (the clip is the question). Needs ffmpeg; the key comes from
ELEVENLABS_API_KEY or a proxy that adds it.
"""
import hashlib, json, math, os, re, struct, subprocess, sys, urllib.request
from concurrent.futures import ThreadPoolExecutor

VOICE, MODEL = "y0SYydk17lMbUIUvSf3N", "eleven_v4"   # AK - British Posh Well-Spoken Old Man
FPS, RATE = 25, 8000
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
os.makedirs("audio/q", exist_ok=True)

def texts():
    """Every question the TV can ask that MacPhisto should read: the trivia, the sorting prompts, the cover prompt."""
    js = "global.window={}; require('./questions.js'); const U=window.U2;" \
         "console.log(JSON.stringify([...U.Q.map(q=>q.q), ...U.ORDER.map(o=>o.q), 'Name the album']))"
    return json.loads(subprocess.run(["node", "-e", js], capture_output=True, text=True, check=True).stdout)

def qid(text): return hashlib.sha1(text.encode()).hexdigest()[:10]

def spoken(text):
    """What he says: no emoji, and a few symbols as words."""
    t = re.sub(r"[\U0001F000-\U0001FAFF\u2600-\u27BF\u2B00-\u2BFF\uFE0F\u200D]", "", text)
    t = t.replace("360°", "three-sixty").replace("°", " degrees").replace("…", "...").replace("___", "blank")
    return "[measured] " + re.sub(r"\s+", " ", t).strip()

def make(text):
    out = f"audio/q/{qid(text)}.mp3"
    if os.path.exists(out): return None
    req = urllib.request.Request(f"https://api.elevenlabs.io/v1/text-to-speech/{VOICE}?output_format=mp3_44100_128",
        data=json.dumps({"text": spoken(text), "model_id": MODEL}).encode(),
        headers={"Content-Type": "application/json", "xi-api-key": os.environ.get("ELEVENLABS_API_KEY", "x")})
    for attempt in range(4):
        try:
            raw = urllib.request.urlopen(req, timeout=120).read(); break
        except urllib.error.HTTPError as e:
            if e.code != 429 or attempt == 3: return f"{text[:50]}: {e.code} {e.read()[:200]!r}"
        except Exception as e:
            if attempt == 3: return f"{text[:50]}: {e}"
    tmp = out + ".raw.mp3"
    open(tmp, "wb").write(raw)
    log = subprocess.run(["ffmpeg", "-nostats", "-i", tmp, "-af", "ebur128", "-f", "null", "-"], capture_output=True, text=True).stderr
    lufs = float(re.findall(r"I:\s+(-?[\d.]+) LUFS", log)[-1])   # same loudness as his other lines
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", tmp, "-af", f"volume={-27.2 - lufs:.1f}dB", "-ar", "44100", "-ac", "1", "-b:a", "128k", out], check=True)
    os.remove(tmp)
    return None

def envelope(path):
    pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"], capture_output=True, check=True).stdout
    x = struct.unpack(f"<{len(pcm) // 2}h", pcm[: len(pcm) // 2 * 2])
    hop, out = RATE // FPS, []
    for i in range(0, len(x), hop):
        w = x[i:i + hop]
        rms = math.sqrt(sum(v * v for v in w) / max(1, len(w))) / 32768
        out.append("0123456789abcdefghijklmnopqrstuvwxyz"[round(max(0, min(1, (rms - 0.012) * 9)) * 35)])
    return "".join(out)

all_texts = texts()
if "--index" not in sys.argv:
    todo = [t for t in all_texts if not os.path.exists(f"audio/q/{qid(t)}.mp3")]
    print(f"{len(todo)} to make", flush=True)
    with ThreadPoolExecutor(3) as pool:   # the plan allows a few requests at once
        for k, err in enumerate(pool.map(make, todo), 1):
            if err: print("failed:", err, flush=True)
            if k % 25 == 0: print(f"{k}/{len(todo)}", flush=True)

index = {}
for t in all_texts:
    path = f"audio/q/{qid(t)}.mp3"
    if not os.path.exists(path): continue
    dur = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path], capture_output=True, text=True).stdout)
    index[t] = {"id": qid(t), "dur": round(dur, 2), "env": envelope(path)}
keep = {v["id"] + ".mp3" for v in index.values()}
for f in os.listdir("audio/q"):   # readings of questions that were edited or removed
    if f.endswith(".mp3") and f not in keep:
        os.remove(f"audio/q/{f}"); print("removed", f)
with open("question-voice.js", "w") as fh:
    fh.write("// Generated by tools/question-voice.py. Don't edit by hand.\n")
    fh.write("// MacPhisto reading each question: audio/q/<id>.mp3, id = first 10 hex of SHA-1 of the question text.\n")
    fh.write("window.QUESTION_VOICE = " + json.dumps(index, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(len(index), "of", len(all_texts), "questions voiced")
